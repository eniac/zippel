#[test]
fn checked_pow_overflow() {
    let a = CRange::new(2, 3);
    let b = CRange::new(64, 65); // 2^64 overflows usize on 64-bit
    assert_eq!(a.checked_pow(b), None);
}

#[test]
fn checked_pow_end_overflow() {
    // (usize::MAX - 1)^2 overflows usize
    let big = usize::MAX - 1;
    let a = CRange::new(big, big + 1); // singleton {big} — big+1 = MAX, fits
    let b = CRange::new(2, 3); // singleton {2}
                               // big^2 overflows
    assert_eq!(a.checked_pow(b), None);
}

#[test]
fn compose_overflow_returns_none() {
    // step * other.step = MAX * 2 overflows
    let a = CRange {
        start: 0,
        step: usize::MAX,
        end: usize::MAX,
    };
    let b = CRange {
        start: 0,
        step: 2,
        end: 3,
    };
    assert_eq!(a.compose(&b), None);
}

#[test]
fn iterator_stops_on_overflow() {
    let r = CRange {
        start: usize::MAX - 1,
        step: 2,
        end: usize::MAX,
    };
    // First: start=MAX-1 (< MAX), yield MAX-1, then start = (MAX-1)+2 overflows → start=end
    let mut it = r;
    assert_eq!(it.next(), Some(usize::MAX - 1));
    assert_eq!(it.next(), None);
}
